const dict = { fr, en } as const;

export type TKey = keyof typeof fr;

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: TKey) => string;
  /** Translate a French UI literal. Returns it unchanged in French mode. */
  tr: (frText: string) => string;
};
const LangCtx = createContext<Ctx>({ lang: "fr", setLang: () => {}, t: (k) => k, tr: (s) => s });

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("fr");
  useEffect(() => {
    try {
      const saved = localStorage.getItem("lang") as Lang | null;
      if (saved === "en" || saved === "fr") {
        setLangState(saved);
        if (typeof document !== "undefined") document.documentElement.lang = saved;
        return;
      }
      const nav = typeof navigator !== "undefined" ? navigator : undefined;
      const candidates: string[] = [
        ...((nav?.languages as string[] | undefined) ?? []),
        nav?.language ?? "",
      ].filter(Boolean);
      const detected: Lang = candidates.some((c) => c.toLowerCase().startsWith("fr"))
        ? "fr"
        : candidates.some((c) => c.toLowerCase().startsWith("en"))
          ? "en"
          : "fr";
      setLangState(detected);
      if (typeof document !== "undefined") document.documentElement.lang = detected;
    } catch {}
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    try { localStorage.setItem("lang", l); } catch {}
    if (typeof document !== "undefined") document.documentElement.lang = l;
  };
  const t = (k: TKey) => (dict[lang][k] ?? dict.fr[k] ?? k);
  const tr = (s: string) => (lang === "en" ? (EN_PHRASES[s] ?? s) : s);
  return <LangCtx.Provider value={{ lang, setLang, t, tr }}>{children}</LangCtx.Provider>;
}

export function useI18n() { return useContext(LangCtx); }

/** Convenience hook: `const tr = useTr()` then `tr("Enregistrer")`. */
export function useTr() { return useContext(LangCtx).tr; }

export function LanguageSwitcher({ size = "sm" }: { size?: "sm" | "default" }) {
  const { lang, setLang, t } = useI18n();
  return (
    <div className="inline-flex items-center gap-1 rounded-md border border-border/60 bg-background/40 p-0.5" role="group" aria-label={t("lang_label")}>
      <Languages className="ml-1 h-3.5 w-3.5 text-muted-foreground" aria-hidden="true" />
      <Button
        type="button"
        size={size}
        variant={lang === "fr" ? "secondary" : "ghost"}
        className="h-7 px-2 text-xs"
        onClick={() => setLang("fr")}
        aria-pressed={lang === "fr"}
      >FR</Button>
      <Button
        type="button"
        size={size}
        variant={lang === "en" ? "secondary" : "ghost"}
        className="h-7 px-2 text-xs"
        onClick={() => setLang("en")}
        aria-pressed={lang === "en"}
      >EN</Button>
    </div>
  );
}
